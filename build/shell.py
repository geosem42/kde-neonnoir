"""The shell prompt from artboard 06: cyan path, magenta branch, a cyan caret.

Colours are ANSI bright indices rather than the palette's hex values. The
terminal already maps those indices through the Neon Noir colour scheme
(brcyan is #36D7D7, brmagenta #F57BEC), so the prompt follows whatever scheme
is active instead of fighting it — and it still reads correctly in a terminal
that never loaded our scheme at all.

Dirtiness is checked with two `git diff --quiet` calls rather than
`git status --porcelain`: status walks untracked files, which is slow enough to
be felt on every prompt in a large tree.
"""

BASH = r'''# Neon Noir prompt. Generated by build/shell.py — do not edit by hand.

__nn_git() {
    local b d=''
    b=$(git symbolic-ref --quiet --short HEAD 2>/dev/null) \
        || b=$(git rev-parse --short HEAD 2>/dev/null) \
        || return 0
    git diff --no-ext-diff --quiet 2>/dev/null \
        && git diff --no-ext-diff --cached --quiet 2>/dev/null \
        || d=' *'
    # \001 and \002 mark non-printing runs. \[ and \] are not interpreted in
    # the output of a command substitution, so using them here would make
    # readline miscount the prompt width and smear the line on every edit.
    printf ' \001\033[95m\002%s\001\033[93m\002%s\001\033[0m\002' "$b" "$d"
}

# The window title is the directory and nothing else. Distributions set this
# to user@host:dir from /etc/bash.bashrc, which puts an account name and a
# machine name in every titlebar and every screenshot of one.
__nn_title='\[\033]0;\w\007\]'

# A blank line before each prompt, as the artboard spaces its commands.
PS1="${__nn_title}"'\n\[\033[96m\]\w\[\033[0m\]$(__nn_git) \[\033[96m\]\342\235\257\[\033[0m\] '
PS2='\[\033[96m\]\342\200\246\[\033[0m\] '
'''

ZSH = r'''# Neon Noir prompt. Generated by build/shell.py — do not edit by hand.

__nn_precmd() {
    local b d=''
    b=$(git symbolic-ref --quiet --short HEAD 2>/dev/null) \
        || b=$(git rev-parse --short HEAD 2>/dev/null)
    if [[ -n $b ]]; then
        git diff --no-ext-diff --quiet 2>/dev/null \
            && git diff --no-ext-diff --cached --quiet 2>/dev/null \
            || d=' *'
        NN_GIT=" %F{13}${b}%f%F{11}${d}%f"
    else
        NN_GIT=""
    fi
}
# The window title is the directory and nothing else. /etc/zsh/zshrc sets it to
# user@host:dir, which puts an account name and a machine name in every
# titlebar and every screenshot of one. This hook is added after that one, so
# it runs last and wins.
__nn_title() { print -Pn '\e]0;%~\a' }
autoload -Uz add-zsh-hook
add-zsh-hook precmd __nn_precmd
add-zsh-hook precmd __nn_title

# PROMPT_SUBST expands ${NN_GIT} first, then the %F escapes inside it. Setting
# the branch in a precmd rather than a $(...) inside PROMPT keeps the prompt
# from forking a subshell on every redraw.
setopt PROMPT_SUBST
PROMPT=$'\n%F{14}%~%f${NN_GIT} %F{14}❯%f '
PROMPT2=$'%F{14}…%f '
'''


def build(DIST, THEME_NAME):
    d = DIST / 'shell'
    d.mkdir(parents=True, exist_ok=True)
    (d / 'prompt.bash').write_text(BASH)
    (d / 'prompt.zsh').write_text(ZSH)
    return ['shell/prompt.bash, shell/prompt.zsh']
