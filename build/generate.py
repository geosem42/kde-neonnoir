#!/usr/bin/env python3
"""Generate every Neon Noir theme artefact from design/palette.json.

The palette is the single source of truth: no hex literal is hand-written into an
output file. Every foreground/background pair a user will actually read is
contrast-asserted here, so an illegible combination fails the build instead of
shipping.
"""
import json, os, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAL  = json.loads((ROOT / 'design' / 'palette.json').read_text())
T    = PAL['tokens']
ANSI = {a['name']: a['hex'] for a in PAL['ansi']}
DIST = ROOT / 'dist'

THEME_ID   = 'NeonNoir'
PKG_ID     = 'org.neonnoir.desktop'
APPLET_ID  = 'org.neonnoir.sysmon'
THEME_NAME = 'Neon Noir'

# ---------- colour helpers ----------
def rgb(h):
    h = h.lstrip('#'); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
def dec(tok):
    r, g, b = rgb(T[tok] if tok in T else tok); return f'{r},{g},{b}'
def _lum(h):
    def f(c):
        c /= 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (f(c) for c in rgb(h)); return .2126 * r + .7152 * g + .0722 * b
def cr(a, b):
    a = T.get(a, a); b = T.get(b, b)
    la, lb = _lum(a), _lum(b); hi, lo = max(la, lb), min(la, lb)
    return (hi + .05) / (lo + .05)

FAILURES = []
def need(fg, bg, target, why):
    r = cr(fg, bg)
    if r < target:
        FAILURES.append(f'{why}: {fg} on {bg} = {r:.2f}, need {target}')
    return r

# ---------- shared foreground set for a .colors group ----------
def fg_set(link='accent.indigo', visited='accent.indigo.visited',
           normal='text.normal', inactive='text.dim', active='accent.cyan',
           neg='status.negative', neu='status.neutral', pos='status.positive'):
    return {
        'ForegroundNormal':   normal,  'ForegroundInactive': inactive,
        'ForegroundActive':   active,  'ForegroundLink':     link,
        'ForegroundVisited':  visited, 'ForegroundNegative': neg,
        'ForegroundNeutral':  neu,     'ForegroundPositive': pos,
        'DecorationFocus':    'decoration.focus',
        'DecorationHover':    'decoration.hover',
    }

# (name, background, alternate, foregrounds, normal-text target)
# Target is AAA (7.0) everywhere a user reads body text. The inactive header is
# the one deliberate exception: it is de-emphasised chrome by definition, so it
# is held to AA against its own alternate rather than AAA.
GROUPS = [
    ('Colors:Window',            'surface.window', 'surface.raised', fg_set(), 7.0),
    ('Colors:View',              'surface.view',   'surface.alt',    fg_set(), 7.0),
    ('Colors:Button',            'surface.raised', 'surface.float',  fg_set(), 7.0),
    ('Colors:Tooltip',           'tooltip.bg',     'surface.float',  fg_set(), 7.0),
    ('Colors:Complementary',     'surface.void',   'surface.view',   fg_set(), 7.0),
    ('Colors:Header',            'titlebar.active','surface.window', fg_set(), 7.0),
    ('Colors:Header][Inactive',  'titlebar.inactive','titlebar.active',
        fg_set(normal='text.dim', inactive='text.title.inactive',
               active='accent.cyan'), 4.5),
    # On a deep-cyan selection a cyan link would vanish and the standard status
    # colours drop to ~3.5:1, so this group uses lightness-lifted variants solved
    # against selection.bg. Breeze plays the same trick in reverse on its light
    # blue selection, darkening them instead.
    ('Colors:Selection',         'selection.bg',   'accent.cyan.dim',
        fg_set(normal='selection.fg', inactive='selection.fg.dim',
               active='selection.fg', link='selection.link',
               visited='accent.magenta.calm',
               neg='selection.negative', neu='selection.neutral',
               pos='selection.positive'), 7.0),
]

def colors_file():
    L = [f'# {THEME_NAME} — generated by build/generate.py; do not edit by hand.',
         '# Source of truth: design/palette.json',
         '# SPDX-License-Identifier: LGPL-2.0-or-later', '']
    # Effects: match Breeze's disabled treatment, keep inactive off (it double-dims
    # an already-dark theme and wrecks the elevation ladder).
    L += ['[ColorEffects:Disabled]', f'Color={dec("surface.raised")}', 'ColorAmount=0',
          'ColorEffect=0', 'ContrastAmount=0.65', 'ContrastEffect=1',
          'IntensityAmount=0.1', 'IntensityEffect=2', '']
    L += ['[ColorEffects:Inactive]', 'ChangeSelectionColor=true',
          f'Color={dec("text.dim")}', 'ColorAmount=0.025', 'ColorEffect=2',
          'ContrastAmount=0.1', 'ContrastEffect=2', 'Enable=false',
          'IntensityAmount=0', 'IntensityEffect=0', '']
    for name, bg, alt, fgs, tgt in GROUPS:
        L.append(f'[{name}]')
        L.append(f'BackgroundAlternate={dec(alt)}')
        L.append(f'BackgroundNormal={dec(bg)}')
        for k in sorted(fgs):
            L.append(f'{k}={dec(fgs[k])}')
        L.append('')
        label = name.replace('Colors:', '')
        need(fgs['ForegroundNormal'], bg, tgt,  f'{label} normal text')
        need(fgs['ForegroundInactive'], bg, 4.5, f'{label} inactive text')
        need(fgs['ForegroundLink'], bg, 4.5,     f'{label} link')
        need(fgs['ForegroundNegative'], bg, 4.5, f'{label} negative')
        need(fgs['ForegroundPositive'], bg, 4.5, f'{label} positive')
        need(fgs['ForegroundNeutral'], bg, 4.5,  f'{label} neutral')
        need(fgs['ForegroundNormal'], alt, tgt,  f'{label} normal text on alternate')
    L += ['[General]', f'ColorScheme={THEME_ID}', f'Name={THEME_NAME}',
          'shadeSortColumn=true', '']
    L += ['[KDE]', 'contrast=4', '']
    L += ['[WM]', f'activeBackground={dec("titlebar.active")}',
          f'activeBlend={dec("text.normal")}', f'activeForeground={dec("text.normal")}',
          f'inactiveBackground={dec("titlebar.inactive")}',
          f'inactiveBlend={dec("text.title.inactive")}',
          f'inactiveForeground={dec("text.title.inactive")}', '']
    need('text.normal', 'titlebar.active', 7.0, 'WM active title')
    need('text.title.inactive', 'titlebar.inactive', 4.5, 'WM inactive title')
    return '\n'.join(L)

def konsole_file():
    faint = {'black':'brblack','red':'red','green':'green','yellow':'yellow',
             'blue':'blue','magenta':'magenta','cyan':'cyan','white':'white'}
    order = ['black','red','green','yellow','blue','magenta','cyan','white']
    L = [f'# {THEME_NAME} — generated by build/generate.py; do not edit by hand.', '']
    for grp, tok in (('Background','surface.view'), ('BackgroundFaint','surface.view'),
                     ('BackgroundIntense','surface.void')):
        L += [f'[{grp}]', f'Color={dec(tok)}', '']
    for i, n in enumerate(order):
        L += [f'[Color{i}]', f'Color={dec(ANSI[n])}', '']
        L += [f'[Color{i}Faint]', f'Color={dec(ANSI[faint[n]])}', '']
        L += [f'[Color{i}Intense]', f'Color={dec(ANSI["br"+n])}', '']
        if n not in ('black',):
            need(ANSI[n], T['surface.view'], 4.5, f'ANSI {n}')
            need(ANSI['br'+n], T['surface.view'], 4.5, f'ANSI bright {n}')
    for grp, tok in (('Foreground','text.normal'), ('ForegroundFaint','text.dim'),
                     ('ForegroundIntense',ANSI['brwhite'])):
        L += [f'[{grp}]', f'Color={dec(tok)}', '']
    need('text.normal', 'surface.view', 7.0, 'Konsole foreground')
    L += ['[General]', f'Description={THEME_NAME}', 'Opacity=0.95', 'Blur=true',
          'ColorRandomization=false', 'Wallpaper=', '']
    return '\n'.join(L)

def kate_theme():
    ec = {
      'BackgroundColor':'surface.view','CodeFolding':'accent.cyan.dim',
      'BracketMatching':'accent.cyan.ghost','CurrentLine':'surface.alt',
      'IconBorder':'surface.window','IndentationLine':'border.hairline',
      'LineNumbers':'text.disabled','CurrentLineNumber':'accent.cyan',
      'MarkBookmark':'accent.indigo','MarkBreakpointActive':'status.negative',
      'MarkBreakpointReached':'status.neutral','MarkBreakpointDisabled':'text.disabled',
      'MarkExecution':'text.dim','MarkWarning':'status.neutral','MarkError':'status.negative',
      'ModifiedLines':'status.neutral','SavedLines':'status.positive',
      'ReplaceHighlight':'status.positive.ghost','SearchHighlight':'status.neutral.ghost',
      'Separator':'border.hairline','SpellChecking':'status.negative',
      'TabMarker':'border.hairline','TemplateBackground':'surface.window',
      'TemplateFocusedPlaceholder':'accent.cyan.ghost','TemplatePlaceholder':'surface.raised',
      'TemplateReadOnlyPlaceholder':'surface.disabled','TextSelection':'selection.bg',
      'WordWrapMarker':'border.hairline',
    }
    ts = {
      'Normal':'text.normal','Keyword':ANSI['brmagenta'],'Function':ANSI['brblue'],
      'Variable':ANSI['brblue'],'ControlFlow':ANSI['brmagenta'],'Operator':ANSI['white'],
      'BuiltIn':ANSI['brmagenta'],'Extension':ANSI['brblue'],'Preprocessor':ANSI['brcyan'],
      'Attribute':ANSI['brcyan'],'Char':ANSI['brgreen'],'SpecialChar':ANSI['brcyan'],
      'String':ANSI['brgreen'],'VerbatimString':ANSI['green'],'SpecialString':ANSI['brcyan'],
      'Import':ANSI['brcyan'],'DataType':ANSI['bryellow'],'DecVal':ANSI['bryellow'],
      'BaseN':ANSI['bryellow'],'Float':ANSI['bryellow'],'Constant':ANSI['bryellow'],
      'Comment':'text.disabled','Documentation':'text.dim','Annotation':ANSI['brcyan'],
      'CommentVar':ANSI['brblue'],'RegionMarker':ANSI['brblue'],'Information':ANSI['bryellow'],
      'Warning':'status.neutral','Alert':'status.negative','Error':'status.negative',
      'Others':ANSI['brgreen'],
    }
    for k, v in ts.items():
        if k not in ('Comment',):   # comments recede on purpose
            need(v, 'surface.view', 4.5, f'syntax {k}')
    return json.dumps({
      'metadata': {'name': THEME_NAME, 'revision': 1,
                   'license': 'SPDX-License-Identifier: MIT',
                   'copyright': ['Neon Noir theme']},
      'editor-colors': {k: T.get(v, v) for k, v in ec.items()},
      'text-styles': {k: {'text-color': T.get(v, v)} for k, v in ts.items()},
      'custom-styles': {},
    }, indent=2) + '\n'

OUT = [
  ('color-schemes/%s.colors' % THEME_ID,            colors_file),
  ('konsole/%s.colorscheme' % THEME_ID,             konsole_file),
  ('syntax-highlighting/neon-noir.theme',           kate_theme),
]

def main():
    for rel, fn in OUT:
        p = DIST / rel; p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(fn())
        print(f'  wrote dist/{rel}  ({p.stat().st_size} bytes)')
    sys.path.insert(0, str(ROOT / 'build'))
    import artefacts, decoration, icons, cursors, brand, kvantum, lookandfeel, sddm, plymouth, plasmoid, apps
    # A folder is a large filled shape: the full-strength UI accent is far too
    # loud across 500 icons, so match Breeze's own folder lightness instead.
    folder_hex = T['accent.cyan.folder']
    for line in icons.build(T, DIST, THEME_ID, THEME_NAME, folder_hex):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in decoration.build(T, DIST, THEME_ID, THEME_NAME, colors_file()):
        print(f'  wrote dist/{line}')
    for line in artefacts.build(T, ANSI, DIST, THEME_ID, THEME_NAME, need, PKG_ID):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in cursors.build(T, DIST, THEME_ID, THEME_NAME):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in brand.build(T, DIST, THEME_ID, THEME_NAME):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in kvantum.build(T, DIST, THEME_ID, THEME_NAME):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in lookandfeel.build(T, DIST, THEME_ID, THEME_NAME, PKG_ID,
                                  widget_style='kvantum'):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in sddm.build(T, DIST, THEME_ID, THEME_NAME, ROOT / 'build' / 'templates'):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in plymouth.build(T, DIST, THEME_ID, THEME_NAME, ROOT / 'build' / 'templates'):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in plasmoid.build(T, DIST, THEME_ID, THEME_NAME, APPLET_ID,
                               ROOT / 'build' / 'templates'):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)
    for line in apps.build(T, ANSI, DIST, THEME_ID, THEME_NAME,
                           artefacts.UI_FONT, artefacts.MONO_FONT,
                           ROOT / 'build' / 'templates'):
        print(f'  wrote dist/{line}' if not line.startswith('  !') else line)

    if FAILURES:
        print(f'\nCONTRAST FAILURES ({len(FAILURES)}):', file=sys.stderr)
        for f in FAILURES: print('  ' + f, file=sys.stderr)
        return 1
    print('\n  all contrast assertions passed')
    return 0

if __name__ == '__main__':
    sys.exit(main())
